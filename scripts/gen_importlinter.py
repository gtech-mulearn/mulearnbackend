"""Write .importlinter from tests/architecture/module_graph.toml.

    python scripts/gen_importlinter.py

Run it after changing the graph and commit both files. tests/architecture/test_importlinter_generated.py
fails when the committed .importlinter differs from what this script writes. See
docs/architecture/04-module-rules.md.
"""

import argparse
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # Python 3.10
    import tomli as tomllib

ROOT = Path(__file__).resolve().parent.parent
GRAPH = ROOT / "tests" / "architecture" / "module_graph.toml"
OUTPUT = ROOT / ".importlinter"

LEGACY_PACKAGES = ["api", "db", "utils", "mu_celery"]

HEADER = """\
# Generated by scripts/gen_importlinter.py from tests/architecture/module_graph.toml.
# Don't edit it: change the graph, run python scripts/gen_importlinter.py, and commit both.
"""


def load_graph(path: Path) -> dict[str, list[str]]:
    """Return the [modules] table: each module and the modules it may depend on."""
    with path.open("rb") as file:
        data = tomllib.load(file)
    if "modules" not in data:
        raise ValueError(f"{path} has no [modules] table.")
    return data["modules"]


def block(key: str, values: list[str]) -> str:
    return f"{key} =\n" + "".join(f"    {value}\n" for value in values)


def render(graph: dict[str, list[str]]) -> str:
    # graph is unused until issue 0023 adds one contract per module.
    return (
        HEADER
        + "\n[importlinter]\n"
        + block("root_packages", ["building_blocks", *LEGACY_PACKAGES])
        + "# Forbidden contracts may name packages that aren't installed or don't exist yet, such as modules.\n"
        + "include_external_packages = True\n"
        + "\n[importlinter:contract:building-blocks]\n"
        + "name = building_blocks imports no business or legacy code\n"
        + "type = forbidden\n"
        + block("source_modules", ["building_blocks"])
        + block("forbidden_modules", ["modules", *LEGACY_PACKAGES])
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--graph", type=Path, default=GRAPH)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)

    args.output.write_bytes(render(load_graph(args.graph)).encode("utf-8"))
    print(f"Wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
